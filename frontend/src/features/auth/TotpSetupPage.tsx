import { useMutation } from '@tanstack/react-query';
import { useEffect, useState, type FormEvent } from 'react';
import { useTranslation } from 'react-i18next';
import { Navigate, useNavigate } from 'react-router-dom';
import { Button } from '@/components/ui/button';
import { Field } from '@/components/ui/field';
import { Input } from '@/components/ui/input';
import { ApiError, authApi } from '@/lib/api';
import { AuthLayout, FormError } from './AuthLayout';
import { useAuth } from './AuthProvider';

export function TotpSetupPage() {
  const { t } = useTranslation();
  const { me, reload } = useAuth();
  const navigate = useNavigate();
  const [code, setCode] = useState('');
  const [error, setError] = useState<string | null>(null);
  const setup = useMutation({ mutationFn: authApi.totpSetup });

  const enabled = me?.totp_enabled ?? false;
  const { mutate } = setup;
  useEffect(() => {
    if (me && !enabled) mutate();
  }, [me, enabled, mutate]);

  if (!me) return <Navigate to="/login" replace />;
  if (enabled) return <Navigate to="/" replace />;

  const onSubmit = async (e: FormEvent) => {
    e.preventDefault();
    setError(null);
    try {
      await authApi.totpVerify(code);
      await reload();
      navigate('/', { replace: true });
    } catch (err) {
      setError(err instanceof ApiError ? err.message : t('auth.unexpected'));
    }
  };

  return (
    <AuthLayout title={t('totp.title')} subtitle={t('totp.subtitle')}>
      <div className="flex flex-col gap-4">
        <FormError message={setup.error instanceof ApiError ? setup.error.message : null} />
        <ol className="list-decimal space-y-1 pl-5 text-body text-fg-body">
          <li>{t('totp.step1')}</li>
          <li>{t('totp.step2')}</li>
          <li>{t('totp.step3')}</li>
        </ol>
        {setup.data && (
          <div
            data-theme="light"
            className="flex flex-col items-center gap-2 rounded-card border border-border bg-surface p-4"
          >
            <div
              role="img"
              aria-label={t('totp.qrLabel')}
              // SVG generated by the backend (segno), not user input.
              dangerouslySetInnerHTML={{ __html: setup.data.qr_svg }}
            />
            <p className="text-caption text-fg-muted">{t('totp.manual')}</p>
            <code className="break-all text-small font-semibold text-fg">{setup.data.secret}</code>
          </div>
        )}
        <form noValidate className="flex flex-col gap-4" onSubmit={onSubmit}>
          <FormError message={error} />
          <Field label={t('login.totp')} required>
            <Input
              inputMode="numeric"
              autoComplete="one-time-code"
              maxLength={6}
              value={code}
              onChange={(e) => setCode(e.target.value)}
            />
          </Field>
          <Button
            type="submit"
            variant="primary"
            className="w-full"
            disabled={!setup.data || code.trim().length !== 6}
          >
            {t('totp.submit')}
          </Button>
        </form>
      </div>
    </AuthLayout>
  );
}
